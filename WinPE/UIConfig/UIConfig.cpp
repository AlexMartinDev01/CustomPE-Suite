/* ============================================================
 * UIConfig 总调度
 * ------------------------------------------------------------
 * UI_ConfigAll()：依序调度三个阶段——
 *   ① 屏幕信息 + 各窗口初始化（UIConfig_Init.cpp）
 *   ② 布局计算（UIConfig_Layout.cpp）
 *   ③ 主题应用（UIConfig_Theme.cpp）
 * 主函数启动时调用一次，之后各窗口创建直接读取全局数组。
 * ============================================================ */
#include "UIConfig.h" // 本模块头

void UI_ConfigAll(void) // 总配置函数：按固定顺序调度所有窗口配置
{
    /* ---- 第一步：屏幕/DPI 与各窗口默认配置 ---- */
    UI_InitScreen();         // ① 屏幕大小 + DPI
    UI_InitWindowMain();     // ② 主窗口初始化
    UI_InitWindowStatus();   // ③ 子窗口①（状态栏）初始化
    UI_InitWindowContent();  // ④ 子窗口②（内容）初始化
    UI_InitWindowBottom();   // ⑤ 子窗口③（底部）初始化

    /* ---- 第二步：一次性计算全部窗口布局 ---- */
    UI_LayoutAll();          // 主窗口（屏幕居中）→ 三子窗口（百分比）

    /* ---- 第三步：应用主题（创建画刷，供窗口类/面板使用） ---- */
    UI_ApplyThemes();        // 依序应用各窗口主题
    UI_ApplyPalette();       // 应用细节调色板（画刷池 4..9）
}
